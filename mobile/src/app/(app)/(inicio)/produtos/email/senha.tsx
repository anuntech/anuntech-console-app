import { useState } from "react";
import { AccessibilityInfo, KeyboardAvoidingView, Platform, ScrollView, View } from "react-native";
import { router, useLocalSearchParams } from "expo-router";
import { useMutation } from "@tanstack/react-query";
import * as Clipboard from "expo-clipboard";
import { Button } from "@/components/button";
import { Field } from "@/components/field";
import { Segmented } from "@/components/segmented";
import { Card, Notice } from "@/components/surface";
import { Text } from "@/components/text";
import { api, errorMessage } from "@/lib/api";
import { showFlash } from "@/lib/flash";
import { haptic } from "@/lib/haptics";
import { refreshMail } from "@/lib/mail";
import { space } from "@/lib/theme";

/**
 * "Trocar senha" of one mailbox (mail.resetPassword), as the web's sheet:
 * generated by the Console and shown once, with copy, or typed (12
 * characters at least; the server checks the strength). The Console keeps
 * no password, so a generated one is gone once this sheet closes.
 */
export default function MailPassword() {
  const { id, address } = useLocalSearchParams<{ id: string; address: string }>();
  const [mode, setMode] = useState<"generate" | "type">("generate");
  const [typed, setTyped] = useState("");
  const [copied, setCopied] = useState(false);
  const reset = useMutation({
    mutationFn: () => api.mail.resetPassword({ id, mode, ...(mode === "type" ? { password: typed } : {}) }),
    onSuccess: async (result) => {
      haptic.success();
      setTyped("");
      await refreshMail();
      // A typed password: nothing to show, back to the mailbox.
      if (!result.password) {
        showFlash(result.message);
        router.back();
      }
    },
    onError: () => haptic.error(),
  });
  const secret = reset.data?.password;
  if (secret)
    return (
      <ScrollView contentInsetAdjustmentBehavior="automatic" contentContainerStyle={{ padding: space.gutter, gap: space.block }}>
        <View style={{ gap: space.xs }}>
          <Text variant="heading" accessibilityRole="header">
            Senha nova
          </Text>
          <Text tone="muted">{reset.data?.message}</Text>
        </View>
        <Card style={{ gap: space.sm }}>
          <Text variant="caption" tone="muted">
            {address}
          </Text>
          {/* The system's monospace keeps look-alike characters apart when the password is read or typed. */}
          <Text
            selectable
            style={{ fontFamily: Platform.OS === "ios" ? "Menlo" : "monospace", fontSize: 18 }}
            accessibilityLabel={`Senha: ${secret.split("").join(" ")}`}
          >
            {secret}
          </Text>
        </Card>
        <Notice kind="warning" title="Guarde agora">
          Ela não aparece de novo: o Console não guarda a senha. Se perder, troque outra vez.
        </Notice>
        <Button
          title={copied ? "Senha copiada" : "Copiar senha"}
          icon={copied ? "checkmark" : "doc.on.doc"}
          onPress={async () => {
            await Clipboard.setStringAsync(secret);
            setCopied(true);
            haptic.success();
            AccessibilityInfo.announceForAccessibility("Senha copiada");
          }}
        />
        <Button title="Pronto" variant="secondary" onPress={() => router.back()} />
      </ScrollView>
    );
  return (
    <KeyboardAvoidingView style={{ flex: 1 }} behavior={Platform.OS === "ios" ? "padding" : undefined}>
      <ScrollView
        contentInsetAdjustmentBehavior="automatic"
        keyboardShouldPersistTaps="handled"
        contentContainerStyle={{ padding: space.gutter, gap: space.block }}
      >
        <Text tone="muted">
          A senha de {address} muda agora no servidor. Os aplicativos conectados com a senha antiga vão pedir a nova.
        </Text>
        <Segmented
          values={["Gerar senha", "Digitar senha"]}
          selectedIndex={mode === "generate" ? 0 : 1}
          onChange={(index) => {
            setMode(index === 0 ? "generate" : "type");
            reset.reset();
          }}
          accessibilityLabel="Como escolher a senha"
        />
        {mode === "generate" ? (
          <Text tone="muted">O Console gera uma senha forte de 24 caracteres e mostra uma vez só, para você copiar.</Text>
        ) : (
          <Field
            label="Senha nova"
            hint="Pelo menos 12 caracteres, sem o endereço da caixa. Abaixo de 16, misture letras com números ou símbolos."
            value={typed}
            onChangeText={(next) => {
              setTyped(next);
              reset.reset();
            }}
            secureTextEntry
            autoCapitalize="none"
            autoCorrect={false}
            textContentType="newPassword"
            autoComplete="new-password"
            maxLength={128}
            returnKeyType="done"
            onSubmitEditing={() => typed.length >= 12 && reset.mutate()}
          />
        )}
        {reset.error ? <Notice kind="error">{errorMessage(reset.error)}</Notice> : null}
        <Button
          title={reset.isPending ? "Trocando…" : mode === "generate" ? "Gerar e trocar a senha" : "Trocar senha"}
          busy={reset.isPending}
          disabled={mode === "type" && typed.length < 12}
          onPress={() => reset.mutate()}
        />
      </ScrollView>
    </KeyboardAvoidingView>
  );
}
